"""Build NHL defense-vs-position snapshots from MoneyPuck game logs.

Writes nhl/dvp_f.json, nhl/dvp_d.json, and nhl/dvp_g.json, then mirrors them
under kbo-props-ui/public/data/nhl/ for the Vite dev fallback. Publish reads
the repo-root copies, same as the other NHL snapshots.

Rank 1 is the toughest matchup (fewest per game). Rank 32 is the easiest.
This does not change projection math.

    python -m nhl.build_dvp --root /tmp/moneypuck
"""
from __future__ import annotations

import argparse
import json
import os
from collections import defaultdict
from pathlib import Path

from nhl.history import load_goalies, load_skaters
from nhl.teams import TEAM_NAMES, team_abbr

ROOT = Path(__file__).resolve().parents[1]
PUBLIC_DIR = ROOT / "kbo-props-ui" / "public" / "data" / "nhl"
HANDOFF_GAMES = 20
CURRENT_SEASON = "20262027"
PRIOR_SEASON = "20252026"
SEASONS = (CURRENT_SEASON, PRIOR_SEASON)
WINDOWS = (
    ("blend", "Season"),
    ("l10", "Last 10"),
    ("l20", "Last 20"),
)
RANK_NOTE = "Rank 1 is the toughest matchup. Rank 32 is the easiest."

# stat id, field on the team-game, button label, sentence under the selector.
FORWARD_STATS = (
    ("sog", "f_sog", "Shots", "Shots on goal allowed to forwards, per game"),
    ("points", "f_pts", "Points", "Points allowed to forwards, per game"),
)
DEFENSE_STATS = (
    ("sog", "d_sog", "Shots", "Shots on goal allowed to defensemen, per game"),
    ("points", "d_pts", "Points", "Points allowed to defensemen, per game"),
)
GOALIE_STATS = (
    ("shots", "shots", "Shots", "Shots generated on the opposing goalie, per game"),
)


def format_date(value: str | None) -> str:
    text = str(value or "")
    if len(text) == 8 and text.isdigit():
        return f"{text[:4]}-{text[4:6]}-{text[6:]}"
    return text


def skater_team_games(rows: list[dict]) -> list[dict]:
    """One row per defensive team-game.

    A game is opened by the first opposing skater. Forward and defense totals
    start at zero, so a position group that did not dress still counts as zero
    in that team's average.
    """
    slots: dict[tuple, dict] = {}
    for row in rows:
        defense = team_abbr(row.get("opp"))
        if defense not in TEAM_NAMES or not row.get("date") or not row.get("game_id"):
            continue
        key = (row.get("season"), row["game_id"], defense)
        slot = slots.get(key)
        if slot is None:
            slot = {
                "season": row.get("season"),
                "game_id": row["game_id"],
                "team": defense,
                "date": row["date"],
                "f_sog": 0.0,
                "f_pts": 0.0,
                "d_sog": 0.0,
                "d_pts": 0.0,
            }
            slots[key] = slot
        if row.get("pos") == "F":
            slot["f_sog"] += float(row.get("sog") or 0)
            slot["f_pts"] += float(row.get("points") or 0)
        elif row.get("pos") == "D":
            slot["d_sog"] += float(row.get("sog") or 0)
            slot["d_pts"] += float(row.get("points") or 0)
    return list(slots.values())


def offense_shot_games(rows: list[dict]) -> list[dict]:
    """Shots on goal by the offense, from the skaters who took them.

    The goalie files count the same shots (ongoal). The refresh often saves the
    skater CSVs and drops the goalie CSVs, so this keeps the goalie table up.
    """
    slots: dict[tuple, dict] = {}
    for row in rows:
        offense = team_abbr(row.get("team"))
        if offense not in TEAM_NAMES or not row.get("date") or not row.get("game_id"):
            continue
        key = (row.get("season"), row["game_id"], offense)
        slot = slots.get(key)
        if slot is None:
            slot = {
                "season": row.get("season"),
                "game_id": row["game_id"],
                "team": offense,
                "date": row["date"],
                "shots": 0.0,
            }
            slots[key] = slot
        slot["shots"] += float(row.get("sog") or 0)
    return list(slots.values())


def goalie_shot_games(rows: list[dict]) -> list[dict]:
    """Shots on goal generated by each offense, summed across the goalies who faced them.

    A game with no goalie row is left out. It is not filled in as zero.
    """
    slots: dict[tuple, dict] = {}
    for row in rows:
        offense = team_abbr(row.get("opp"))
        if offense not in TEAM_NAMES or not row.get("date") or not row.get("game_id"):
            continue
        key = (row.get("season"), row["game_id"], offense)
        slot = slots.get(key)
        if slot is None:
            slot = {
                "season": row.get("season"),
                "game_id": row["game_id"],
                "team": offense,
                "date": row["date"],
                "shots": 0.0,
            }
            slots[key] = slot
        slot["shots"] += float(row.get("sa") or 0)
    return list(slots.values())


def _mean(rows: list[dict], stat: str) -> float:
    return sum(float(row[stat]) for row in rows) / len(rows)


def window_summary(rows: list[dict], stat: str, window: str, current: str, prior: str, handoff: int) -> dict | None:
    usable = [row for row in rows if row.get("season") in (current, prior)]
    if window == "blend":
        this = [row for row in usable if row.get("season") == current]
        last = [row for row in usable if row.get("season") == prior]
        gp = len(this)
        prior_gp = len(last)
        if gp == 0 and prior_gp == 0:
            return None
        if gp == 0:
            used = last
            value = _mean(last, stat)
            weight = 0.0
        elif prior_gp == 0 or gp >= handoff:
            used = this
            value = _mean(this, stat)
            weight = 1.0
        else:
            used = this + last
            weight = gp / handoff
            value = weight * _mean(this, stat) + (1.0 - weight) * _mean(last, stat)
        return {
            "value": value,
            "gp": gp,
            "priorGames": prior_gp,
            "weight": weight,
            "through": max(row["date"] for row in used),
        }
    if window in ("l10", "l20"):
        count = 10 if window == "l10" else 20
        ordered = sorted(usable, key=lambda row: (row.get("date") or "", row.get("game_id") or ""))
        used = ordered[-count:]
        if not used:
            return None
        return {
            "value": _mean(used, stat),
            "gp": len(used),
            "priorGames": 0,
            "weight": 1.0,
            "through": used[-1]["date"],
        }
    raise ValueError(window)


def sample_label(window: str, summary: dict) -> str:
    gp = int(summary["gp"])
    prior = int(summary["priorGames"])
    if window == "blend":
        if gp == 0:
            return f"last season · {prior} gp"
        if float(summary["weight"]) < 1:
            return f"{gp} this season · {prior} last season"
        return f"{gp} gp"
    return f"{gp} gp"


def rank_teams(entries: list[dict]) -> list[dict]:
    """Rank 1 is the lowest per-game number. Ties break by team code.

    The returned list is easiest first (rank 32 at the top).
    """
    ordered = sorted(entries, key=lambda row: (row["value"], row["team"]))
    ranked = []
    for index, row in enumerate(ordered, start=1):
        ranked.append({**row, "rank": index})
    ranked.sort(key=lambda row: (-row["rank"], row["team"]))
    return ranked


def _team_index(games: list[dict]) -> dict[str, list[dict]]:
    by_team: dict[str, list[dict]] = defaultdict(list)
    for game in games:
        if game.get("season") in SEASONS and game.get("team") in TEAM_NAMES:
            by_team[game["team"]].append(game)
    missing = sorted(set(TEAM_NAMES) - set(by_team))
    if missing:
        raise SystemExit(f"NHL DvP expected all 32 teams, missing {', '.join(missing)}")
    return by_team


def build_snapshot(games: list[dict], position: str, label: str, stats: tuple) -> dict:
    by_team = _team_index(games)
    windows = {}
    for window_id, window_label in WINDOWS:
        stat_payloads = {}
        for stat_id, field, stat_label, detail in stats:
            entries = []
            for team in sorted(TEAM_NAMES):
                summary = window_summary(by_team[team], field, window_id, CURRENT_SEASON, PRIOR_SEASON, HANDOFF_GAMES)
                if summary is None:
                    raise SystemExit(f"{team} has no {position} {stat_id} games")
                entries.append({
                    "team": team,
                    "name": TEAM_NAMES[team],
                    "gp": summary["gp"],
                    "priorGames": summary["priorGames"],
                    "weight": round(summary["weight"], 4),
                    "value": round(summary["value"], 3),
                    "sample": sample_label(window_id, summary),
                    "through": format_date(summary["through"]),
                })
            ranked = rank_teams(entries)
            stat_payloads[stat_id] = {
                "label": stat_label,
                "detail": detail,
                "leagueAvg": round(sum(row["value"] for row in ranked) / len(ranked), 3),
                "teams": ranked,
            }
        windows[window_id] = {"id": window_id, "label": window_label, "stats": stat_payloads}
    dates = [game["date"] for game in games if game.get("season") in SEASONS and game.get("date")]
    if not dates:
        raise SystemExit(f"NHL DvP {position} has no games")
    return {
        "position": position,
        "label": label,
        "sourceThrough": format_date(max(dates)),
        "handoffGames": HANDOFF_GAMES,
        "rankNote": RANK_NOTE,
        "windows": windows,
    }


def build_snapshots(root: Path) -> dict[str, dict]:
    skater_rows = load_skaters(root, years=("2025", "2026"))
    skaters = skater_team_games(skater_rows)
    goalies = goalie_shot_games(load_goalies(root, years=("2025", "2026")))
    if not goalies and skaters:
        print(f"NHL DvP goalie logs missing under {root}; counting shots from skaters")
        goalies = offense_shot_games(skater_rows)
    if not skaters or not goalies:
        raise SystemExit(f"NHL DvP found no MoneyPuck games under {root}")
    return {
        "dvp_f.json": build_snapshot(skaters, "F", "Forwards", FORWARD_STATS),
        "dvp_d.json": build_snapshot(skaters, "D", "Defense", DEFENSE_STATS),
        "dvp_g.json": build_snapshot(goalies, "G", "Goalies", GOALIE_STATS),
    }


def write_snapshots(payloads: dict[str, dict], out_dir: Path, mirror_dir: Path | None = None) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    if mirror_dir is not None:
        mirror_dir.mkdir(parents=True, exist_ok=True)
    for name, payload in payloads.items():
        text = json.dumps(payload, indent=2) + "\n"
        path = out_dir / name
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path}")
        if mirror_dir is not None:
            mirror = mirror_dir / name
            mirror.write_text(text, encoding="utf-8")
            print(f"wrote {mirror}")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Build NHL defense vs position snapshots")
    parser.add_argument("--root", default=os.environ.get("NHL_MONEYPUCK_ROOT", "/tmp/moneypuck"))
    parser.add_argument("--out", default=str(ROOT / "nhl"))
    args = parser.parse_args(argv)
    out_dir = Path(args.out)
    mirror = PUBLIC_DIR if out_dir.resolve() == (ROOT / "nhl").resolve() else None
    try:
        payloads = build_snapshots(Path(args.root))
    except SystemExit as exc:
        print(exc)
        print("keeping the previous NHL DvP files")
        return 0
    write_snapshots(payloads, out_dir, mirror)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
