function nflGame(spec) {
  return makeGame({
    ...spec,
    books: 12,
    surface: spec.surface || 'Outdoors',
    hits: spec.hits || hits(60, 50, 55, 52),
    matchups: {
      away_off: statRows(NFL_STATS, spec.awayLines),
      home_off: statRows(NFL_STATS, spec.homeLines),
    },
    pace: paceBlock(
      ['SECS/PLAY', 'PLAYS/G'],
      spec.paceAway,
      spec.paceHome,
      'EXP PLAYS',
      spec.expected,
      'SECS/PLAY BY SITUATION',
      spec.situational,
    ),
    dvp: dvpBlock(['QB', 'RB', 'WR', 'TE'], spec.awayDvp, spec.homeDvp),
    components: componentRows(spec.parts),
  })
}

