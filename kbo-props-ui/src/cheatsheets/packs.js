function hoopGame(spec) {
  return makeGame({
    ...spec,
    books: 12,
    surface: 'Indoor',
    hits: spec.hits,
    matchups: {
      away_off: statRows(spec.labels || HOOP_STATS, spec.awayLines),
      home_off: statRows(spec.labels || HOOP_STATS, spec.homeLines),
    },
    pace: paceBlock(
      ['POSS/G', 'SEC/POSS'],
      spec.paceAway,
      spec.paceHome,
      'EXP POSS',
      spec.expected,
      'PACE BY SITUATION',
      spec.situational,
    ),
    dvp: dvpBlock(spec.dvpLabels, spec.awayDvp, spec.homeDvp),
    components: componentRows(spec.parts),
  })
}

